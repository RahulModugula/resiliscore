import { readFile } from "node:fs/promises";
import { expect,test } from "@playwright/test";

for (const viewport of [{name:"desktop",width:1440,height:1000},{name:"mobile",width:390,height:844}]) {
test(`${viewport.name}: map exposes the building demo and opens its controls directly`, async ({page}) => {
  await page.setViewportSize({width:viewport.width,height:viewport.height});
  const apiRequests: string[] = [];
  await page.route("**/v1/**", route => { apiRequests.push(route.request().url()); return route.abort("connectionrefused"); });
  await page.goto("/");
  const entry = page.getByRole("button", {name:"Try building demo", exact:true});
  await expect(entry).toBeInViewport();
  await entry.click();
  await expect(page).toHaveURL(/workflow=demo/);
  await expect(page.getByRole("heading", {name:"Underwriting demo",exact:true})).toBeVisible();
  await page.getByRole("button", {name:/Financial District/}).click();
  await expect(page).toHaveURL(/neighborhood=MN0101.*workflow=demo/);
  await page.getByRole("searchbox",{name:"Find a property by address, BIN, or BBL"}).fill("207 FRONT STREET");
  await page.getByRole("button",{name:"Demo 207 FRONT STREET",exact:true}).first().click();
  await expect(page).toHaveURL(/assessment\?property=.*workflow=demo/);
  await expect(page.getByRole("region",{name:"Selected building underwriting demo"})).toBeVisible();
  await expect(page.getByRole("heading",{name:"Building underwriting demo",exact:true})).toBeInViewport();
  expect(apiRequests).toEqual([]);
  await page.getByRole("link",{name:"Back to Manhattan map",exact:true}).click();
  await expect(page).toHaveURL(/neighborhood=MN0101.*workflow=demo/);
  await expect(page.getByRole("heading",{name:"Underwriting demo",exact:true})).toBeVisible();
  await page.reload();
  await expect(page.getByRole("heading",{name:"Underwriting demo",exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Exit building demo",exact:true}).click();
  await page.getByRole("searchbox",{name:"Find a property by address, BIN, or BBL"}).fill("207 FRONT STREET");
  await expect(page.getByRole("button",{name:"Assess 207 FRONT STREET",exact:true}).first()).toBeVisible();
  await expect(page.getByRole("button",{name:"Try building demo",exact:true})).toBeVisible();
  expect(new URL(page.url()).searchParams.has("workflow")).toBe(false);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});

test(`${viewport.name}: real map building supports offline mitigation, review and a building-specific demo receipt`, async ({page}) => {
  test.setTimeout(60_000);
  await page.setViewportSize({width:viewport.width,height:viewport.height});
  const errors: string[] = [], apiRequests: string[] = [];
  page.on("pageerror",error => errors.push(error.message));
  await page.route("**/v1/**",route => {apiRequests.push(route.request().url());return route.abort("connectionrefused");});
  await page.goto("/?neighborhood=MN0101");
  await expect(page.getByRole("list",{name:"Properties",exact:true})).toBeVisible();
  await page.getByRole("searchbox",{name:"Find a property by address, BIN, or BBL"}).fill("207 FRONT STREET");
  await page.getByRole("button",{name:"Assess 207 FRONT STREET",exact:true}).first().click();
  await expect(page).toHaveURL(/assessment\?property=/);
  const buildingId = new URL(page.url()).searchParams.get("property")!;
  const saved = await page.evaluate(id => sessionStorage.getItem(`resiliscore:manhattan:assessment:v1:${id}`),buildingId);
  await expect(page.getByTestId("selected-building-marker")).toHaveAttribute("data-property-id",buildingId);
  const initialRequests = apiRequests.length;
  await page.getByRole("button",{name:"Open underwriting demo",exact:true}).click();
  const demo = page.getByRole("region",{name:"Selected building underwriting demo"});
  await expect(demo).toBeVisible();
  await expect(demo.getByRole("heading",{name:"Building underwriting demo",exact:true})).toBeFocused();
  await expect(demo.getByRole("heading",{name:"Building underwriting demo",exact:true})).toBeInViewport();
  await expect(demo.getByText(/nonlocal reference tract/)).toBeVisible();
  const bind = demo.getByRole("button",{name:"Prepare demo binding receipt",exact:true});
  await expect(bind).toBeDisabled();
  const beforeLoss = await demo.getByTestId("building-demo-loss").textContent();
  await demo.getByRole("checkbox",{name:/Assume a Class 4 impact-resistant roof/}).check();
  await expect(demo.getByTestId("building-demo-loss")).not.toHaveText(beforeLoss!);
  await demo.getByRole("button",{name:"Open demo verification",exact:true}).click();
  const review = page.getByRole("dialog",{name:"Demo property verification"});
  await expect(review.getByRole("button",{name:"Accept demo evidence",exact:true})).toBeDisabled();
  await review.getByRole("button",{name:"Run simulated building capture",exact:true}).click();
  await review.getByRole("button",{name:"Accept demo evidence",exact:true}).click();
  await expect(bind).toBeEnabled();
  await bind.click();
  const receipt = page.getByRole("dialog",{name:"Selected building demo receipt"});
  await expect(receipt.getByText(/No policy has been issued/)).toBeVisible();
  const downloaded = page.waitForEvent("download");
  await receipt.getByRole("button",{name:"Download building demo receipt",exact:true}).click();
  const download = await downloaded;
  const payload = JSON.parse(await readFile((await download.path())!,"utf8"));
  const recorded = JSON.parse(saved!).result.parcel;
  expect(payload.building_id).toBe(buildingId);
  expect(payload.demo).toBe(true);
  expect(payload.no_policy_issued).toBe(true);
  expect(payload.action_plan).toEqual(["HAIL_CLASS4_ROOF"]);
  expect(payload.footprint).toEqual(recorded.parcel_identity.geometries);
  expect(payload.policy_number).toBeNull();
  await receipt.getByRole("button",{name:"Close dialog",exact:true}).click();
  await demo.getByRole("checkbox",{name:/Assume a Class 4 impact-resistant roof/}).uncheck();
  await expect(bind).toBeDisabled();
  expect(await page.evaluate(id => sessionStorage.getItem(`resiliscore:manhattan:assessment:v1:${id}`),buildingId)).toBe(saved);
  expect(apiRequests.length).toBe(initialRequests);
  await page.getByRole("button",{name:"Return to assessment",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Property risk assessment",exact:true})).toBeVisible();
  await expect(demo).toHaveCount(0);
  await expect(page.getByTestId("selected-building-marker")).toHaveAttribute("data-property-id",buildingId);
  expect(errors).toEqual([]);
});

}
